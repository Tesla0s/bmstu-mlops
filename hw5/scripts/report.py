"""Сводка двух полных прогонов; числа читаются из фактических метрик."""

import json
from pathlib import Path

from src.config import load_params


def main():
    p = load_params()
    names = [v["name"] for v in p["variants"]]
    runs = [json.loads(Path(f"metrics/train_{n}.json").read_text()) for n in names]
    a, f = runs
    assert a["max_steps"] is None and f["max_steps"] is None
    lines = [
        "# Результаты двух полных прогонов LoRA",
        "",
        (
            "Задача: классификация обращений GitHub на bug, feature_request и question. "
            "Отчёт создан из JSON-метрик; значения относятся к нашему датасету, а не к примеру курса."
        ),
        "",
        "## Одинаковые условия",
        "",
        (
            f"База: {a['model']}, ревизия {a['model_revision']}. "
            f"Устройство: {a['device']}; базовые веса: {a['dtype']}."
        ),
        (
            "Apple M3 Pro, 36 ГБ общей памяти. LoRA: r=8, alpha=16, dropout=0.05; "
            "семь проекций внимания и полносвязных слоёв. Шаг обучения 0.0002; seed=42."
        ),
        "",
        (
            f"Вход: {a['train_examples']} train и {a['val_examples']} val из ДЗ4. "
            "Одна эпоха, эффективный батч 8. Ограничения max_steps и val_limit выключены. "
            "Итоговая тестовая часть ДЗ3 не используется."
        ),
        "",
        "## Численное сравнение",
        "",
        "| Показатель | Все 28 слоёв | Только слои 14–27 |",
        "|---|---:|---:|",
    ]
    fields = [
        ("Обучаемых параметров", "trainable_params", "d"),
        ("Всего параметров с адаптером", "total_params", "d"),
        ("Доля обучаемых", "trainable_share", ".3%"),
        ("Шагов оптимизатора", "steps", "d"),
        ("Использовано примеров", "examples_seen", "d"),
        ("Входных токенов обработано", "input_tokens_seen", "d"),
        ("Обучаемых токенов обработано", "supervised_tokens_seen", "d"),
        ("Val loss до обучения", "base_val_loss", ".6f"),
        ("Val loss после эпохи", "final_val_loss", ".6f"),
        ("Обучение без оценки, с", "seconds", ".1f"),
        ("Оценка, с", "eval_seconds", ".1f"),
        ("Обучение вместе с оценкой, с", "wall_seconds", ".1f"),
        ("В среднем на шаг без оценки, с", "seconds_per_step", ".3f"),
        ("Полезных входных токенов/с без оценки", "train_tokens_per_sec", ".1f"),
        ("Наблюдаемый максимум памяти MPS, МиБ", "peak_memory_mb", ".1f"),
        ("Наблюдаемый максимум памяти процесса, МиБ", "peak_rss_mb", ".1f"),
        ("Только матрицы адаптера, МиБ", "adapter_weights_mb", ".2f"),
        ("Папка с токенизатором, МиБ", "adapter_size_mb", ".2f"),
    ]
    for label, key, fmt in fields:
        lines.append(f"| {label} | {format(a[key], fmt)} | {format(f[key], fmt)} |")
    lines += [
        "",
        (
            "Время измерено после загрузки модели: включает прямые и обратные проходы, "
            "обновления параметров и подготовку батчей. Оценка включает исходную точку, "
            "замеры каждые 10 шагов и финальный замер. Загрузка и сохранение отдельно в эти "
            "интервалы не входят."
        ),
        "",
        (
            "Память MPS опрашивается каждые 0,1 с во время обучения и оценки. Это наблюдаемый "
            "максимум занятой драйвером памяти, включая кэш; очень короткий всплеск может "
            "не попасть в выборку. Память процесса приведена отдельно и не заменяет память MPS. "
            "Все размеры памяти и файлов в таблице используют 1 МиБ = 2²⁰ байт."
        ),
        "",
        "## Кривые и сохранность данных",
        "",
        "![Ошибки обучения и проверки](curves.png)",
        "",
        (
            "Train loss — среднее по обучаемым токенам текущей группы примеров. "
            "Val loss — среднее по всем обучаемым токенам всей проверочной выборки. "
            "Метки −100 исключают промпт и дополнение из ошибки, но контекст модели доступен полностью."
        ),
        "",
        (
            f"У каждого варианта {len(a['curve_val'])} точек val: шаг 0, затем 10, 20, …, 160 и 165. "
            "Последний шаг использует оставшиеся три примера и нормируется по их фактическому "
            "числу обучаемых токенов. Данные не обрезались и не подменялись укороченной выборкой."
        ),
        "",
        "## Что изменилось при заморозке",
        "",
        (
            f"Число обучаемых параметров уменьшилось в {a['trainable_params'] / f['trainable_params']:.1f} раза. "
            f"Отношение времени чистого обучения freeze14/all_layers: {f['seconds'] / a['seconds']:.3f}; "
            f"отношение наблюдаемой памяти: {f['peak_memory_mb'] / a['peak_memory_mb']:.3f}."
        ),
        (
            "Это два последовательных измерения на одном ноутбуке, а не многократный "
            "сравнительный эксперимент. На время влияют температура и фоновые задачи. "
            "Повторный расчёт активаций при обратном проходе включён у обоих вариантов, "
            "а входным активациям включён requires_grad. Поэтому обратный проход сохраняется "
            "и через нижние слои freeze14; число обучаемых матриц уменьшается, но вся эта "
            "часть вычислений автоматически не исчезает. Двукратное ускорение не ожидается."
        ),
        "",
        "## Сопоставление с прогнозом ДЗ4",
        "",
    ]
    hw4 = json.loads(Path("../hw4/metrics/tokenize.json").read_text())["train_time_estimate"]
    epoch_forecast = [v / hw4["epochs"] for v in hw4["training_hours_range"]]
    lines += [
        (
            f"В ДЗ4 для трёх эпох было получено {hw4['training_hours_range'][0]:.3f}–"
            f"{hw4['training_hours_range'][1]:.3f} ч. На одну эпоху это "
            f"{epoch_forecast[0]:.3f}–{epoch_forecast[1]:.3f} ч. "
            f"Фактическое время all_layers: {a['seconds'] / 3600:.3f} ч чистого обучения "
            f"или {a['wall_seconds'] / 3600:.3f} ч с регулярной оценкой."
        ),
        "",
        (
            "Прогноз ДЗ4 опирался на последовательную генерацию и условный множитель 2–3. "
            "Дообучение обрабатывает известные токены параллельно, а в этой задаче выходные "
            "вероятности нужны только для 8–9 токенов ответа. Поэтому такой прогноз не является "
            "точной моделью времени данного цикла. Данные измерения заменяют приблизительную оценку."
        ),
        "",
        "## Границы вывода",
        "",
        (
            "Снижение val loss показывает уменьшение ошибки предсказания отложенных ответов, "
            "в том числе освоение формата JSON. Оно не равно измерению точности классификации. "
            "Пять фиксированных запросов в compare.md демонстрируют работу адаптера, "
            "но недостаточны для статистически обоснованного сравнения качества."
        ),
        "",
        (
            "Проверка повторяемости относится к закреплённым библиотекам, устройству и коротким "
            "прогонам с одинаковым seed. Побитовое совпадение между разным оборудованием не обещается."
        ),
        "",
    ]
    Path("docs/training_report.md").write_text("\n".join(lines))
    print("-> docs/training_report.md")


if __name__ == "__main__":
    main()
